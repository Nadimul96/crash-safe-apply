#!/usr/bin/env node
// Runs the same fault-injection matrix as the tests and writes
// docs/fault-matrix.md: totals, and every crash point of apply and rollback.
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { applyMatrix, doubleFaultMatrix, rollbackMatrix } from "../test/support/fault-matrix.js";

/** @import { MatrixResult } from "../test/support/fault-matrix.js" */

const repo = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const started = Date.now();
const results = [await applyMatrix(), await rollbackMatrix(), await doubleFaultMatrix(3)];
const seconds = ((Date.now() - started) / 1000).toFixed(1);
const [applyResult, rollbackResult, doubleResult] = results;
if (!applyResult || !rollbackResult || !doubleResult) throw new Error("matrix did not run");

const points = results.reduce((sum, r) => sum + r.points.length, 0);
const recoveries = results.reduce((sum, r) => sum + r.recoveries, 0);
const torn = results.reduce(
	(sum, r) => sum + r.points.filter((p) => p.op === "write-partial").length,
	0,
);
const fsyncs = results.reduce(
	(sum, r) => sum + r.points.filter((p) => p.op.startsWith("fsync")).length,
	0,
);

/** @param {MatrixResult} result */
const table = (result) =>
	[
		"| # | step | operation | path |",
		"|--:|---|---|---|",
		...result.points.map((p) => `| ${p.seq} | ${p.step} | \`${p.op}\` | \`${p.path}\` |`),
	].join("\n");

/** @param {MatrixResult} result */
const seen = (result) =>
	Object.entries(result.statusSeen)
		.map(([state, count]) => `${state}: ${count}`)
		.join(", ");

const machine = `${os.cpus()[0]?.model ?? "unknown CPU"}, ${os.type()} ${os.release()}, Node ${process.version}`;
const report = `# Fault-injection matrix

Generated by \`pnpm fault-report\` on ${new Date().toISOString().slice(0, 10)} (${machine}); took ${seconds} s.
The same matrix runs in \`pnpm test\` (\`test/fault-*.test.js\`).

**${points} crash points, ${recoveries} recoveries verified, 0 failures.** ${fsyncs} of the points sit right after an fsync and ${torn} are torn writes (only the first half of a write on disk).

How it works: every mutating filesystem call goes through one I/O layer
([src/io.js](../src/io.js)), which calls a hook after each step. A run first
records every step; then, for each step, a fresh copy of the scenario is
crashed right after it (the hook throws, and the I/O layer refuses all later
mutations, so no cleanup runs). After every crash the test checks:

- \`status\` agrees with the disk: \`not-applied\` or \`restored\` only if the tree is byte-identical to the original, \`complete\` only if it is byte-identical to the applied tree;
- \`rollback\` restores a byte-identical original tree;
- re-running \`apply\` converges on the applied tree.

The scenario ([test/support/scenario.js](../test/support/scenario.js)) replaces one file, creates two in existing
and new directories, creates one executable file in another new directory, and leaves one file unchanged.

| Matrix | Crash points | Recoveries | Status reported after the crash |
|---|--:|--:|---|
| apply | ${applyResult.points.length} | ${applyResult.recoveries} | ${seen(applyResult)} |
| rollback of a complete apply | ${rollbackResult.points.length} | ${rollbackResult.recoveries} | ${seen(rollbackResult)} |
| double fault (apply crashes, then the recovery crashes) | ${doubleResult.points.length} | ${doubleResult.recoveries} | ${seen(doubleResult)} |

This models process death (kill -9, OOM kill, a panic). It does not simulate
power loss, where unsynced data can vanish; that guarantee rests on the fsync
ordering described in the README. Real \`kill -9\` runs of a separate process
are in [test/sigkill.test.js](../test/sigkill.test.js).

## Every apply step

${table(applyResult)}

## Every rollback step

${table(rollbackResult)}
`;

await fs.writeFile(path.join(repo, "docs", "fault-matrix.md"), report);
process.stdout.write(
	`${points} crash points, ${recoveries} recoveries verified in ${seconds} s -> docs/fault-matrix.md\n`,
);
