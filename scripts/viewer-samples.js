#!/usr/bin/env node
// Produces viewer/samples.js from real runs of the library against the demo
// bundle in examples/: a clean apply, a crash that tears a journal record, a
// crash followed by a resumed apply, and a refused apply that is rolled back.
// The temp target path in each journal is replaced with a neutral one and the
// records are re-encoded so their checksums stay valid.
import { writeFileSync } from "node:fs";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { apply, preview, rollback } from "../src/index.js";
import { decodeJournal, encodeRecord } from "../src/journal.js";
import { crashAt } from "../test/support/faults.js";

const repo = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const bundle = path.join(repo, "examples", "demo-bundle");
const SHOWN_TARGET = "/srv/demo-service";

/**
 * @param {(target: string, plan: string) => Promise<void>} scenario
 * @returns {Promise<string>} the journal text
 */
async function capture(scenario) {
	const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), "csa-sample-")));
	try {
		const target = path.join(root, "demo-service");
		await fs.cp(path.join(repo, "examples", "demo-target"), target, { recursive: true });
		const plan = (await preview({ bundle, target })).id;
		await scenario(target, plan);
		const stateDir = path.join(target, ".crash-safe-apply");
		const [bundleId] = (await fs.readdir(stateDir)).filter((name) => name !== "lock");
		const journal = await fs.readFile(path.join(stateDir, bundleId ?? "", "1", "journal.log"));
		return neutralize(journal, target);
	} finally {
		await fs.rm(root, { recursive: true, force: true });
	}
}

/**
 * @param {Buffer} journal
 * @param {string} target
 */
function neutralize(journal, target) {
	const view = decodeJournal(journal);
	const lines = journal.subarray(0, view.validBytes).toString("utf8").trimEnd().split("\n");
	const records = lines.map((line) => JSON.parse(line.slice(9)));
	const first = records[0];
	if (first.target !== target) throw new Error("unexpected target in journal");
	first.target = SHOWN_TARGET;
	const text = records.map((record) => encodeRecord(record).toString("utf8")).join("");
	return text + journal.subarray(view.validBytes).toString("utf8");
}

const expectFailure = (/** @type {Promise<unknown>} */ run) =>
	run.then(
		() => {
			throw new Error("expected the run to stop");
		},
		() => undefined,
	);

const samples = [
	{
		id: "applied",
		label: "Applied and verified",
		description:
			"A clean run: originals backed up, five bundle files compared, four written, every file read back.",
		journal: await capture(async (target, plan) => {
			await apply({ bundle, target, plan });
		}),
	},
	{
		id: "killed",
		label: "Killed mid-apply",
		description:
			"The process died while appending a journal record, after config/app.toml was published. The torn record fails its checksum.",
		journal: await capture(async (target, plan) => {
			let seen = 0;
			await expectFailure(
				apply({
					bundle,
					target,
					plan,
					faults: crashAt(
						(p) => p.op === "write-partial" && p.step === "journal: file record" && ++seen === 4,
					),
				}),
			);
		}),
	},
	{
		id: "resumed",
		label: "Interrupted, then finished",
		description:
			"A crash right after config/features.json was linked into place, then apply was run again and converged.",
		journal: await capture(async (target, plan) => {
			await expectFailure(
				apply({
					bundle,
					target,
					plan,
					faults: crashAt((p) => p.op === "link" && p.path === "config/features.json"),
				}),
			);
			await apply({ bundle, target, plan });
		}),
	},
	{
		id: "refused",
		label: "Refused, then rolled back",
		description:
			"Another program created config/features.json during the apply. Apply refused to overwrite it and stopped as incomplete; rollback restored everything else.",
		journal: await capture(async (target, plan) => {
			await expectFailure(
				apply({
					bundle,
					target,
					plan,
					faults: (p) => {
						if (p.op === "rename" && p.step === "publish config/app.toml") {
							writeFileSync(
								path.join(target, "config", "features.json"),
								'{ "owner": "someone else" }\n',
							);
						}
					},
				}),
			);
			await rollback({ bundle, target });
		}),
	},
];

const out = path.join(repo, "viewer", "samples.js");
const body = `// Generated by scripts/viewer-samples.js from real runs against examples/. Do not edit by hand.\nwindow.JOURNAL_SAMPLES = ${JSON.stringify(samples, null, "\t")};\n`;
await fs.writeFile(out, body);
process.stdout.write(`Wrote ${samples.length} samples to ${path.relative(repo, out)}\n`);
